export const PROVINCE_BY_CODE = new Map(
	PROVINCES.map((province) => [province.code, province]),
);

export const MUNICIPALITY_BY_CODE = new Map(
	PROVINCES.flatMap((province) =>
		province.municipalities.map(
			(municipality) =>
				[municipality.code, { ...municipality, province }] as const,
		),
	),
);

export type LocationMunicipalityWithProvince = LocationMunicipality & {
	province: LocationProvince;
};

/** Municípios de uma província, ou lista vazia se o código não existir. */
export function municipalitiesOf(provinceCode: string): LocationMunicipality[] {
	return PROVINCE_BY_CODE.get(provinceCode)?.municipalities ?? [];
}

/** Província de um município, ou `undefined` se o código não existir. */
export function provinceOf(
	municipalityCode: string,
): LocationProvince | undefined {
	return MUNICIPALITY_BY_CODE.get(municipalityCode)?.province;
}
